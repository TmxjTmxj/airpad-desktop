"""Deterministic replay regression over the scripted landmark fixture.

The fixture holds 21-landmark observations generated by tools/hand_model.py, so this runs
the real geometry gate, the real hand selector and the real gesture state machine -- the
same chain the camera feeds. It is synthetic (see tools/make_fixture.py): it proves the
pipeline is deterministic and produces the intended actions, and is not evidence about
recognizer accuracy on real hands.
"""
import json
from collections import Counter
from pathlib import Path

import pytest

from airpad.config import Profile
from airpad.core import GestureEngine
from airpad.geometry import FingerStability, HandSelector, extract_sample
from airpad.types import HandSample

FIXTURE = Path(__file__).resolve().parent / 'fixtures' / 'landmarks' / 'pointer.jsonl'
KINDS = ('click', 'left_down', 'left_up', 'move', 'wheel', 'zoom', 'release_all')


class Row:
    __slots__ = ('t', 'state', 'reason', 'actions', 'valid')

    def __init__(self, t, state, reason, actions, valid):
        self.t, self.state, self.reason, self.actions, self.valid = t, state, reason, actions, valid

    def kinds(self):
        return [kind for kind, _, _ in self.actions]


def replay(path=FIXTURE):
    """Run the fixture through the same chain `python -m airpad replay --experimental` uses.

    The fixture exercises two-finger scrolling, which is opt-in, so the profile enables it
    here exactly as the CLI flag does.
    """
    profile = Profile(two_finger_scroll=True, three_finger_enabled=True)
    engine = GestureEngine(profile)
    selector = HandSelector(profile.dominant_hand)
    stability = FingerStability()
    width, height = 640, 480
    trace = []
    with Path(path).open(encoding='utf-8-sig') as stream:
        for line in stream:
            if not line.strip():
                continue
            row = json.loads(line)
            kind = row.get('type')
            if kind == 'header':
                width, height = int(row.get('width', width)), int(row.get('height', height))
                continue
            if kind == 'lost':
                actions = engine.step(None, float(row['t']))
                trace.append(Row(row['t'], engine.state, 'lost', _tuple(actions), False))
                continue
            if kind == 'landmarks':
                t = float(row['t'])
                hands = [{'landmarks': row['landmarks'],
                          'handedness': row.get('handedness', 'Unknown'),
                          'handedness_score': row.get('handedness_score', 0.0)}]
                chosen = selector.select(hands, t)
                sample, quality = None, {'valid': False}
                if chosen is not None:
                    sample, quality = extract_sample(chosen, t, int(row.get('width', width)),
                                                     int(row.get('height', height)),
                                                     selector.track_id, stability)
                actions = engine.step(sample, t)
                trace.append(Row(row['t'], engine.state, selector.reason, _tuple(actions),
                                 quality.get('valid', False)))
            else:
                sample = HandSample(**{k: v for k, v in row.items() if k != 'type'})
                actions = engine.step(sample, sample.t)
                trace.append(Row(row['t'], engine.state, 'legacy sample', _tuple(actions), True))
    return trace


def _tuple(actions):
    return tuple((a.kind, a.x, a.y) for a in actions)


def kinds(trace):
    return Counter(kind for row in trace for kind in row.kinds())


def stamps(trace, kind):
    return [row.t for row in trace if kind in row.kinds()]


@pytest.fixture(scope='module')
def trace():
    assert FIXTURE.is_file(), 'run tools/make_fixture.py to generate the fixture'
    return replay()


def test_fixture_declares_itself_synthetic():
    header = json.loads(FIXTURE.read_text(encoding='utf-8').splitlines()[0])
    assert header['type'] == 'header'
    assert header['source'] == 'synthetic-scripted'
    assert 'not recorded from a person' in header['note'].lower()
    assert header['schema'] == 'airpad.replay/2'


def test_replay_is_deterministic():
    assert [r.actions for r in replay()] == [r.actions for r in replay()]


def test_geometry_gate_accepts_the_scripted_hand(trace):
    """Every scripted frame must pass the geometry gate and be attributed to one hand.

    The first frames are the hysteresis warming up, so a couple of them report no pose;
    anything beyond that would mean the gate is rejecting a valid hand.
    """
    warmup = [row for row in trace if row.t <= 0.20]
    settled = [row for row in trace if row.t > 0.20 and row.reason != 'lost']
    assert all(row.valid for row in settled), \
        'the scripted hand must satisfy the same quality gate a real hand does'
    assert len(warmup) <= 8
    detected = sum(1 for row in trace if row.reason == 'Hand detected')
    assert detected >= len(trace) - 2


def test_scripted_cycle_produces_exactly_one_click(trace):
    counts = kinds(trace)
    assert counts['click'] == 1
    assert counts['left_down'] == 1, 'the click must not also press the button'
    assert stamps(trace, 'click')[0] < stamps(trace, 'left_down')[0]


def test_scripted_drag_presses_and_releases_exactly_once(trace):
    downs, ups = stamps(trace, 'left_down'), stamps(trace, 'left_up')
    assert len(downs) == 1 and len(ups) == 1
    assert downs[0] < ups[0]


def test_pointer_sweep_and_drag_emit_relative_motion(trace):
    moves = [a for row in trace for a in row.actions if a[0] == 'move']
    assert len(moves) >= 20, 'the sweep and the drag should both produce movement'
    assert all(x or y for _, x, y in moves), 'no empty move actions'


def test_two_finger_segment_scrolls_and_never_clicks(trace):
    counts = kinds(trace)
    assert counts['wheel'] >= 5
    assert counts['zoom'] == 0, 'zoom is opt-in and the default profile keeps it disabled'


def test_hand_loss_releases_everything_once(trace):
    releases = stamps(trace, 'release_all')
    assert releases, 'losing the hand must release held input'
    lost_at = trace[-1].t
    for row in trace:
        if row.t >= lost_at:
            assert not set(row.kinds()) & {'click', 'left_down', 'move', 'wheel', 'zoom'}


def test_nothing_is_acted_on_before_the_pointer_is_armed(trace):
    """The first frames are an open palm; nothing may be held or clicked there."""
    for row in trace:
        if row.t <= 0.30:
            assert not set(row.kinds()) & {'click', 'left_down', 'move', 'wheel', 'zoom'}
            assert row.state in ('READY', 'CLUTCH', 'LOST_TRACKING')


def test_state_machine_reaches_the_expected_states(trace):
    states = {row.state for row in trace}
    assert {'CLUTCH', 'TRACKING', 'PINCH_HOLD', 'DRAGGING', 'SCROLLING'} <= states
